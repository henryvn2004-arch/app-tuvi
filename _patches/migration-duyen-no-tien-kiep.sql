create table if not exists public.past_life_bonds (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null references auth.users(id) on delete cascade,
  created_at    timestamptz not null default now(),
  -- Loại duyên (khoá cổ pháp) + nhãn tiếng Việt. Lưu CẢ HAI: khoá để truy vấn
  -- và thống kê, nhãn để hiện lại lịch sử mà không phải đồng bộ bảng tra trong
  -- code — đổi chữ trong engine thì bản đã lưu vẫn đọc đúng như lúc người ta xem.
  bond_kind     text,
  bond_label    text,
  character_a   text,
  character_b   text,
  occupation_a  text,
  occupation_b  text,
  era           text,
  image_url     text not null,
  -- Khoá canonical của CẶP lá số (đã sắp thứ tự) — xem normalizePair trong
  -- app/api/duyen-no-tien-kiep/route.ts. Đây cũng là chỗ tra "user này đã trả
  -- cho cặp lá số nào" để cho xem lại miễn phí.
  laso_key      text
);

create index if not exists past_life_bonds_user_idx on public.past_life_bonds (user_id, created_at desc);
create index if not exists past_life_bonds_laso_idx on public.past_life_bonds (laso_key);

alter table public.past_life_bonds enable row level security;

-- Cùng khuôn RLS với `past_life_portraits`: chủ sở hữu đọc bản của mình; ghi
-- chỉ qua service key (route server), không mở cho anon/authenticated.
drop policy if exists past_life_bonds_owner_read on public.past_life_bonds;
create policy past_life_bonds_owner_read on public.past_life_bonds
  for select using (auth.uid() = user_id);

drop policy if exists past_life_bonds_admin_read on public.past_life_bonds;
create policy past_life_bonds_admin_read on public.past_life_bonds
  for select using (auth.jwt() ->> 'email' = 'admin@tuviminhbao.com');

