-- Bảng RIÊNG chứ không nhét vào `past_life_portraits`: bảng kia trả lời "lá số
-- này ra nhân vật gì" (một người, một chức phận, một tuổi vẽ), bảng này trả lời
-- "cặp lá số này ra mối duyên gì" (hai nhân vật, một loại duyên). Nhồi chung
-- thì quá nửa số cột luôn NULL ở một trong hai bên, và `action=history` của cả
-- hai tool phải học cách bỏ qua dòng của tool kia.
--
-- ⚠️ `tool_pricing` CỐ Ý `enabled=false`: `cong-cu.html` và `tuvi-paywall.js`
-- đều lọc `enabled=eq.true`, bật TRƯỚC khi deploy là công cụ hiện trên trang
-- Công Cụ trong khi trang chưa tồn tại ⇒ 404 cho người thật. Bật sau khi deploy
-- bằng câu SQL ghi ở cuối file.
